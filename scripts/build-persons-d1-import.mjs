#!/usr/bin/env node
/**
 * Emit the SQL that loads the browse persons index into the civgraph-elections D1.
 *
 * WHY THIS EXISTS
 *
 * The persons index is 11,964 people across three shards under
 * data/browse/person-shards/, totalling 24 MB. It was sharded because a single
 * persons.json reached 25.18 MB and breached Cloudflare Pages' 25 MB per-file limit --
 * a scaling response that kept the file deployable without changing what it is.
 *
 * What it is, is the wrong shape for the commonest operation. Resolving ONE person means
 * fetching and scanning shards until a match. On 2026-08-23 that broke outright: the
 * index had been sharded into a manifest with no `items` array while app/src/app.js still
 * read `payload.items`, so it resolved to [], every person link in the election panes
 * silently did nothing, and no test, validator or error surfaced it. A point lookup
 * against a scanned blob has no good failure mode.
 *
 * Parties in the same app already avoid this -- they have per-entity detail files under
 * data/browse/details/parties/. Persons, the type with 12,000 records, got bulk shards.
 *
 * WHY THE ELECTIONS DATABASE
 *
 * These people ARE election people: the index is a derived aggregate over candidatures,
 * and civgraph-elections already holds `candidates` with a `person_id` column and a
 * `cand_person` index. Putting the aggregate anywhere else would separate it from the
 * rows it is derived from.
 *
 * WHY A BLOB COLUMN AND NOT A FULL NORMAL FORM
 *
 * Same reasoning as build-catalogue-d1-import.mjs, and deliberately the same shape so
 * there is one convention rather than two. A person record carries nested `parties`,
 * `constituencies`, `elections` and `totals` arrays; a faithful relational schema for
 * that is a project of its own, and every field it failed to model would be silently
 * lost on import. So the record is stored whole as JSON in `record`, and only the fields
 * actually queried by are lifted into real columns beside it. The parity validator
 * reconstructs the original document and compares, which makes the import provably
 * lossless. Columns can be promoted out of the blob later without another migration.
 *
 * The static shards are NOT removed by this. They still feed the semantic graph build and
 * the browse fallback, and the R2/Pages copy stays until D1 is proven in production --
 * the same staged cutover functions/data/graph/[[path]].js documents for the graph.
 *
 *   node scripts/build-persons-d1-import.mjs
 *   node scripts/build-persons-d1-import.mjs --check
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const MANIFEST = 'data/browse/persons.json';
const OUT = 'data/database/persons-d1-import.sql';
const CHECK = process.argv.includes('--check');

// D1 rejects very large single statements. The catalogue importer settled on 60 KB and
// there is no reason for persons to differ.
const MAX_STATEMENT_BYTES = 60 * 1024;

const q = (value) => (value === undefined || value === null
  ? 'NULL'
  : `'${String(value).replace(/'/g, "''")}'`);
const n = (value) => (Number.isFinite(Number(value)) ? Number(value) : 'NULL');
const j = (value) => (value === undefined ? 'NULL' : `'${JSON.stringify(value).replace(/'/g, "''")}'`);

/** Read the sharded index the same way browse.js does, so this cannot drift from it. */
function readPersons() {
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  if (manifest.indexLayout !== 'sharded' || !Array.isArray(manifest.shards)) {
    return Array.isArray(manifest.items) ? manifest.items : [];
  }
  const items = [];
  for (const shard of manifest.shards) {
    // shard.url is site-absolute; on disk it is repo-relative.
    const path = String(shard.url || '').replace(/^\//, '');
    if (!existsSync(path)) throw new Error(`shard missing on disk: ${shard.url}`);
    const doc = JSON.parse(readFileSync(path, 'utf8'));
    items.push(...(Array.isArray(doc.items) ? doc.items : []));
  }
  return items;
}

const persons = readPersons();
if (!persons.length) {
  console.error(`FAIL: no person records read from ${MANIFEST}.`);
  process.exit(1);
}

const lines = [];
lines.push('-- GENERATED by scripts/build-persons-d1-import.mjs. Do not edit by hand.');
lines.push('-- Source: data/browse/persons.json (+ person-shards). Target: civgraph-elections.');
lines.push('PRAGMA foreign_keys=OFF;');
lines.push('DROP TABLE IF EXISTS browse_persons;');
lines.push('');
lines.push(`CREATE TABLE browse_persons (
  slug                   TEXT PRIMARY KEY,
  id                     TEXT,
  name                   TEXT,
  -- Lower-cased name, so a lookup can be case-insensitive without a scan. SQLite's
  -- LIKE is case-insensitive for ASCII only, and these names carry fadas.
  name_norm              TEXT,
  first_year             INTEGER,
  last_year              INTEGER,
  name_count             INTEGER,
  related_election_count INTEGER,
  ord                    INTEGER NOT NULL,
  record                 TEXT NOT NULL
);`);
// ord preserves the source array order. Browse relies on index ordering in places, and
// ORDER BY slug would silently reshuffle the whole list.
lines.push('CREATE INDEX idx_browse_persons_name_norm ON browse_persons(name_norm);');
lines.push('CREATE INDEX idx_browse_persons_years ON browse_persons(first_year, last_year);');
lines.push('CREATE INDEX idx_browse_persons_id ON browse_persons(id);');
lines.push('');

const cols = '(slug, id, name, name_norm, first_year, last_year, name_count, related_election_count, ord, record)';
const rowSql = (p, ord) => `(${[
  q(p.slug), q(p.id), q(p.name || p.title),
  q(String(p.name || p.title || '').toLowerCase()),
  n(p.firstYear), n(p.lastYear), n(p.nameCount), n(p.relatedElectionCount),
  ord, j(p),
].join(', ')})`;

let batch = [];
let batchBytes = 0;
let chunked = 0;
const flush = () => {
  if (!batch.length) return;
  lines.push(`INSERT INTO browse_persons ${cols} VALUES\n${batch.join(',\n')};`);
  batch = [];
  batchBytes = 0;
};

/**
 * Write one record whose SQL is too large for a single statement.
 *
 * Two rows are: the referendum pseudo-people "Yes" and "No", which this index aggregates
 * as if they were candidates, so they accumulate 1,207 elections each -- 427 KB apiece,
 * against a median person record of 0.9 KB. D1 rejects statements well below that.
 *
 * The record is APPENDED in chunks rather than truncated. Dropping the tail would make
 * the import lossy, and losing data quietly to satisfy a size limit is precisely the
 * failure the parity validator exists to catch. Each statement stays small; the stored
 * value ends up whole.
 */
const writeChunked = (person, ord) => {
  chunked += 1;
  const json = JSON.stringify(person);
  const size = 40 * 1024;
  const parts = [];
  for (let at = 0; at < json.length; at += size) parts.push(json.slice(at, at + size));
  const esc = (text) => `'${text.replace(/'/g, "''")}'`;
  lines.push(`INSERT INTO browse_persons ${cols} VALUES (${[
    q(person.slug), q(person.id), q(person.name || person.title),
    q(String(person.name || person.title || '').toLowerCase()),
    n(person.firstYear), n(person.lastYear), n(person.nameCount), n(person.relatedElectionCount),
    ord, esc(parts[0]),
  ].join(', ')});`);
  for (let part = 1; part < parts.length; part += 1) {
    lines.push(`UPDATE browse_persons SET record = record || ${esc(parts[part])} WHERE slug = ${q(person.slug)};`);
  }
};

for (let i = 0; i < persons.length; i += 1) {
  const row = rowSql(persons[i], i);
  if (row.length > MAX_STATEMENT_BYTES) { flush(); writeChunked(persons[i], i); continue; }
  if (batch.length && batchBytes + row.length > MAX_STATEMENT_BYTES) flush();
  batch.push(row);
  batchBytes += row.length;
}
flush();
lines.push('');

const sql = `${lines.join('\n')}\n`;

if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== sql) {
    console.error(`FAIL: ${OUT} is stale -- it does not match ${MANIFEST}.`);
    console.error('  Deploying a stale import silently reinstates the old records.');
    console.error('  Regenerate: node scripts/build-persons-d1-import.mjs');
    process.exit(1);
  }
  console.log(`PASS: ${OUT} matches ${MANIFEST} (${persons.length} persons).`);
  process.exit(0);
}

writeFileSync(OUT, sql);
const statements = sql.split(';\n').length - 1;
const largest = Math.max(...sql.split(';\n').map((s) => s.length));
console.log(`Persons D1 import written.`);
console.log(`  persons         : ${persons.length}`);
console.log(`  statements      : ${statements} (${chunked} record(s) appended in chunks)`);
console.log(`  largest stmt    : ${(largest / 1024).toFixed(1)} KB (D1 limit ~100 KB)`);
console.log(`  written         : ${OUT} (${(sql.length / 1024 / 1024).toFixed(2)} MB)`);
