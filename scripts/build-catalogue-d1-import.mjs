#!/usr/bin/env node
/**
 * Emit the SQL that loads data/database/maps.json into the civgraph-catalogue D1.
 *
 * WHY A BLOB COLUMN AND NOT A FULL NORMAL FORM
 *
 * The catalogue records carry ~44 distinct fields between them, most optional
 * and several nested (files, variants, members, sourceDownloads, style). A
 * faithful relational schema for that is a project of its own, and every field
 * it failed to model would be silently lost on import — which for a store that
 * holds licence and attribution is the worst possible failure.
 *
 * So each record is stored whole, as JSON, in `record`, and the fields the
 * application actually queries by are lifted into real columns beside it. That
 * makes the import provably lossless (the parity validator reconstructs the
 * original document and compares), while still allowing the queries that
 * motivate the move: by id, by slug, by category, and "visible layers only".
 * Columns can be promoted out of the blob later without another migration.
 *
 * The non-map top-level keys (categories, classes, c1s, timeSeriesChains) are
 * kept in catalogue_parts so the API can reassemble the exact document shape
 * dataService already expects. That is what makes the client cutover a
 * one-line change rather than a refactor.
 *
 * Usage: node scripts/build-catalogue-d1-import.mjs [--out <path>]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const SRC = 'data/database/maps.json';
const CHECK = process.argv.includes('--check');
const outArg = process.argv.indexOf('--out');
const OUT = outArg >= 0 ? process.argv[outArg + 1] : 'data/database/catalogue-d1-import.sql';

// D1 rejects a single SQL statement over ~100 KB. Batching by ROW COUNT does
// not work here: records average 0.95 KB but the largest is 9 KB, so a fixed 40
// rows produced a 142 KB statement depending on which records happened to land
// together. Batching by accumulated byte size is bounded regardless of
// distribution. 60 KB leaves room for the escaping expansion that happens after
// the size is measured.
const MAX_STATEMENT_BYTES = 60 * 1024;

const doc = JSON.parse(readFileSync(SRC, 'utf8'));
const maps = doc.maps || [];
if (!maps.length) throw new Error('no maps in source');

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v === undefined ? 'NULL' : `'${JSON.stringify(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? 1 : 0);

const lines = [];
lines.push('-- Generated by scripts/build-catalogue-d1-import.mjs. Do not edit.');
lines.push('-- Regenerate after any change to data/database/maps.json.');
lines.push('');
lines.push('DROP TABLE IF EXISTS maps;');
lines.push('DROP TABLE IF EXISTS catalogue_parts;');
lines.push('');
lines.push(`CREATE TABLE maps (
  id          TEXT PRIMARY KEY,
  slug        TEXT,
  name        TEXT,
  description TEXT,
  category    TEXT,
  date        TEXT,
  hidden      INTEGER NOT NULL DEFAULT 0,
  placeholder INTEGER NOT NULL DEFAULT 0,
  featured    INTEGER NOT NULL DEFAULT 0,
  is_group    INTEGER NOT NULL DEFAULT 0,
  parent_id   TEXT,
  provider    TEXT,
  ord         INTEGER NOT NULL,
  record      TEXT NOT NULL
);`);
lines.push('CREATE INDEX idx_maps_category ON maps(category);');
lines.push('CREATE INDEX idx_maps_slug ON maps(slug);');
lines.push('CREATE INDEX idx_maps_hidden ON maps(hidden);');
lines.push('CREATE INDEX idx_maps_parent ON maps(parent_id);');
lines.push('');
lines.push(`CREATE TABLE catalogue_parts (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);`);
lines.push('');

// `ord` preserves the source array order. The application relies on catalogue
// ordering in places, and ORDER BY id would silently reshuffle the whole list.
const cols = '(id, slug, name, description, category, date, hidden, placeholder, featured, is_group, parent_id, provider, ord, record)';
const rowSql = (m, ord) => `(${[
  q(m.id), q(m.slug), q(m.name), q(m.description), q(m.category), q(m.date),
  b(m.hidden), b(m.placeholder), b(m.featured), b(m.isGroup),
  q(m.parentId), j(m.provider), ord, j(m),
].join(', ')})`;

let batch = [];
let batchBytes = 0;
const flush = () => {
  if (!batch.length) return;
  lines.push(`INSERT INTO maps ${cols} VALUES\n${batch.join(',\n')};`);
  batch = [];
  batchBytes = 0;
};
for (let i = 0; i < maps.length; i++) {
  const row = rowSql(maps[i], i);
  if (batch.length && batchBytes + row.length > MAX_STATEMENT_BYTES) flush();
  batch.push(row);
  batchBytes += row.length;
}
flush();
lines.push('');

for (const key of Object.keys(doc)) {
  if (key === 'maps') continue;
  lines.push(`INSERT INTO catalogue_parts (key, value) VALUES (${q(key)}, ${j(doc[key])});`);
}
lines.push('');

const sql = `${lines.join('\n')}\n`;
// --check turns the generator into its own validator, which is the house convention:
// a separate checker would be a second implementation of the same derivation, and two
// implementations of one value is exactly how the value drifts.
//
// WHY THIS EXISTS AT ALL. The D1 parity check was network-only -- it compared
// maps.json against the live /_api/catalogue endpoint -- and it lived in `npm run
// check`, which scripts/README.md promises is entirely offline. So a contributor with
// no network, or with no deploy yet, got either a red gate or a SKIP that proved
// nothing. Worse, the failure it usually reported was not "D1 is wrong" but "you edited
// maps.json and did not regenerate the SQL" -- a purely local mistake, diagnosed by a
// round trip to production.
//
// That local half is this. The remote half stays in verify:catalogue-d1, where it
// belongs, and now means only what it says: the loaded database matches the file that
// was loaded.
if (CHECK) {
  const existing = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
  if (existing === null) {
    console.error(`FAIL: ${OUT} does not exist. Generate it with: node scripts/build-catalogue-d1-import.mjs`);
    process.exit(1);
  }
  if (existing !== sql) {
    console.error(`FAIL: ${OUT} is stale -- it does not match ${SRC}.`);
    console.error("  Every catalogue edit needs the import regenerated, or the next D1 load");
    console.error("  silently reinstates the old records.");
    console.error("  Regenerate: node scripts/build-catalogue-d1-import.mjs");
    process.exit(1);
  }
  console.log(`PASS: ${OUT} matches ${SRC} (${maps.length} maps).`);
  process.exit(0);
}

writeFileSync(OUT, sql);

const biggest = Math.max(...sql.split(';\n').map((s) => s.length));
console.log('Catalogue D1 import');
console.log(`  maps            : ${maps.length}`);
console.log(`  other top keys  : ${Object.keys(doc).filter((k) => k !== 'maps').join(', ')}`);
console.log(`  statements      : ${sql.split(';\n').length - 1}`);
console.log(`  largest stmt    : ${(biggest / 1024).toFixed(1)} KB (D1 limit ~100 KB)`);
console.log(`  written         : ${OUT} (${(sql.length / 1048576).toFixed(2)} MB)`);
if (biggest > 90 * 1024) {
  console.error('FAIL: a statement is close to the D1 limit; lower ROWS_PER_STATEMENT.');
  process.exit(1);
}
